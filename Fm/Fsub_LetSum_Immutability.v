(** #<a name="lemma_5.7"></a># Lemma 5.7 *)
(** Thesis: Lemma (the second lemma:un-safety-step-exists: stripping tags never makes a term stuck), §4.1.2. *)
Lemma safety_step' : forall e s f ns f' ns',
  expr e ->
  expr f ->
  well_formed_store s ->
  qualcomp_store s ns ->
  qualcomp e f ->
  red f ns f' ns' ->
  (exists e' s', red e s e' s' /\ qualcomp_store s' ns' /\ qualcomp e' f').
Proof with eauto; try solve [simpl; eauto; intuition].
------
  intros * ExprE ExprF WfS sLns eLf Redf.
  generalize dependent ns'.
  generalize dependent f'.
  dependent induction eLf; intros; try solve [try inversion Redf; eauto].
  Case "red_app". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf1 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_app e' e2)... exists s'...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf1 _) as ValueE1...
      edestruct IHeLf2 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_app e1 e')... exists s'...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf1 _) as ValueE1...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf2 _) as ValueE2...
      inversion ValueE1; inversion eLf1; subst; try discriminate...
      inversion select (exp_abs _ _ _ = exp_abs _ _ _); subst.
      exists (open_ee e0 e2)... exists s...
  }
  Case "red_tapp". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_tapp e' T)... exists s'...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_tabs _ _ _ = exp_tabs _ _ _); subst...
      exists (open_te e0 T)... exists s...
  }
  Case "red_qapp". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_qapp e' Q)... exists s'...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_qabs _ _ _ = exp_qabs _ _ _); subst...
      exists (open_qe e0 Q)... exists s...
  }
  Case "red_let". { 
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf1 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      eexists... exists s'... split...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf1 _) as ValueE1...
      exists (open_ee e2 e1)... exists s... split...
  }
  Case "red_box". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      eexists... eexists...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      eexists. eexists. split...
      erewrite <- consistent_fresh_label_for_store with (s := ns)...
      eapply consistent_store_symmetric.
      apply qualcomp_stores_are_consistent...
  }
  Case "red_unbox". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      eexists... eexists...
    + inversion eLf; subst...
      inversion select (expr (exp_ref_label _ _ )); subst...
      destruct (sLns) as [Left Right]...
      destruct (Right l f') as [v' [MapS' e'Lv']]...
      unshelve epose proof ((proj1 (LabelMapFacts.find_mapsto_iff ns' l f')) _) as R1...
      unshelve epose proof ((proj1 (LabelMapFacts.find_mapsto_iff s l v')) _) as R2...
      exists v'... exists s...
  }
  Case "red_set_box". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf1 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_set_ref e' e2). eexists...
    + edestruct IHeLf2 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_set_ref e1 e'). eexists... split...
      constructor...
      eapply qualcomp_value with (f := f1)...
    + inversion eLf1; subst...
      inversion select (expr (exp_ref_label _ _ )); subst...
      inversion select (_ ≤ _); subst...
      destruct (sLns) as [Left Right]...
      destruct (Right l f') as [f'' [MapsF LtF]]...
      exists f''... eexists. split...
      econstructor...
      eapply qualcomp_value...
  }
  Case "red_check". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_check Q e')... exists s'...
    + simpl in *.
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_abs _ _ _ = exp_abs _ _ _); subst...
      eexists. eexists. split...
      eapply red_check_abs with (cQ := cqua_bot)...
      destruct cP...
    + simpl in *.
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_tabs _ _ _ = exp_tabs _ _ _); subst...
      eexists. eexists. split...
      eapply red_check_tabs with (cQ := cqua_bot)...
      destruct cP...
    + simpl in *.
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_qabs _ _ _ = exp_qabs _ _ _); subst...
      eexists. eexists. split...
      eapply red_check_qabs with (cQ := cqua_bot)...
      destruct cP... 
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_check_inl with (cQ := cqua_bot)...
      destruct cP...
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_check_inr with (cQ := cqua_bot)...
      destruct cP...
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_check_pair with (cQ := cqua_bot)...
      destruct cP...
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_check_ref_label with (cQ := cqua_bot)...
      destruct cP...
  }
  Case "red_upqual". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_upqual qua_bot e')... exists s'...
    + simpl in *.
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_abs _ _ _ = exp_abs _ _ _); subst...
      eexists. eexists. split...
      eapply red_upqual_abs with (cP := cqua_bot) (cQ := cqua_bot)...
    + simpl in *.
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_tabs _ _ _ = exp_tabs _ _ _); subst...
      eexists. eexists. split...
      eapply red_upqual_tabs with (cP := cqua_bot) (cQ := cqua_bot)...
    + simpl in *.
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      inversion select (exp_qabs _ _ _ = exp_qabs _ _ _); subst...
      eexists. eexists. split...
      eapply red_upqual_qabs with (cP := cqua_bot) (cQ := cqua_bot)... 
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_upqual_inl with (cP := cqua_bot) (cQ := cqua_bot)...
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_upqual_inr with (cP := cqua_bot) (cQ := cqua_bot)...
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_upqual_pair with (cP := cqua_bot) (cQ := cqua_bot)...
    + simpl in *.
      inversion eLf; subst...
      unshelve epose proof (qualcomp_value _ _ _ _ eLf _) as ValueE1...
      inversion ValueE1; inversion eLf; subst; try discriminate...
      eexists. eexists. split...
      eapply red_upqual_ref_label with (cP := cqua_bot) (cQ := cqua_bot)...
  }
  Case "red_inl". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_inl qua_bot e')... exists s'...
  }
  Case "red_inr". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_inr qua_bot e')... exists s'...
  }
  Case "red_case". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf1 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_case e' e2 e3)... exists s'...
      split...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf1 _) as ValueE1...
      inversion ValueE1; inversion eLf1; subst; try discriminate...
      inversion select (exp_inl _ _ = exp_inl _ _); subst...
      exists (open_ee e2 e0)... exists s...
      split...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf1 _) as ValueE1...
      inversion ValueE1; inversion eLf1; subst; try discriminate...
      inversion select (exp_inr _ _ = exp_inr _ _); subst...
      exists (open_ee e3 e0)... exists s...
      split...
  }
  Case "red_pair". {
    inversion ExprE; inversion ExprF; inversion Redf; subst...
    + edestruct IHeLf1 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_pair qua_bot e' e2)... exists s'...
    + unshelve epose proof (qualcomp_value _ _ _ _ eLf1 _) as ValueE1...
      edestruct IHeLf2 with (ns' := ns') as [e' [s' [Rede [SealS2 Seal2]]]]...
      exists (exp_pair qua_bot e1 e')... exists s'...
