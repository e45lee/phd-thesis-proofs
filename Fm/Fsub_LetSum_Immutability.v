(**
  In order to prove that we can adjust tags freely upwards whenever the typing judgment
  allows us to do so we need a notion of when two expressions are "equivalent" modulo
  tags.

  [qualcomp] captures this notion.  Whenever we have qualcomp e1 e2, we know
  that e2 is equivalent to e1 except with tags twiddled in e2 to the least-
  restrictive e1 (with qualifiers all set at bot).
*)
(** Thesis: Definition (stripped term, s ◁ t), §4.1.2. *)
Inductive qualcomp : exp -> exp -> Prop :=
  | qualcomp_fvar : forall (x : atom),
      qualcomp x x
  | qualcomp_bvar : forall (n : nat),
      qualcomp n n
  | qualcomp_abs : forall Q T e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_abs qua_bot T e1) (exp_abs Q T e2)
  | qualcomp_app : forall e1 e2 f1 f2,
      qualcomp e1 f1 ->
      qualcomp e2 f2 ->
      qualcomp (exp_app e1 e2) (exp_app f1 f2)
  | qualcomp_tabs : forall Q T e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_tabs qua_bot T e1) (exp_tabs Q T e2)
  | qualcomp_tapp : forall T e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_tapp e1 T) (exp_tapp e2 T)
  | qualcomp_qabs : forall Q T e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_qabs qua_bot T e1) (exp_qabs Q T e2)
  | qualcomp_qapp : forall Q e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_qapp e1 Q) (exp_qapp e2 Q)
  | qualcomp_let : forall e1 e2 f1 f2,
      qualcomp e1 f1 ->
      qualcomp e2 f2 ->
      qualcomp (exp_let e1 e2) (exp_let f1 f2)
  | qualcomp_box : forall Q e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_ref qua_bot e1) (exp_ref Q e2)
  | qualcomp_unbox : forall e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_deref e1) (exp_deref e2)
  | qualcomp_set_box : forall e1 e2 f1 f2,
      qualcomp e1 f1 ->
      qualcomp e2 f2 ->
      qualcomp (exp_set_ref e1 e2) (exp_set_ref f1 f2)
  | qualcomp_ref_label : forall Q l,
      qualcomp (exp_ref_label qua_bot l) (exp_ref_label Q l)
  | qualcomp_check : forall Q e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_check Q e1) (exp_check Q e2)
  | qualcomp_upqual : forall Q e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_upqual qua_bot e1) (exp_upqual Q e2)
  | qualcomp_inl : forall Q e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_inl qua_bot e1) (exp_inl Q e2)
  | qualcomp_inr : forall Q e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_inr qua_bot e1) (exp_inr Q e2)
  | qualcomp_case : forall e1 e2 f1 f2 e3 f3,
      qualcomp e1 f1 ->
      qualcomp e2 f2 ->
      qualcomp e3 f3 ->
      qualcomp (exp_case e1 e2 e3) (exp_case f1 f2 f3)
  | qualcomp_pair : forall Q e1 e2 f1 f2,
      qualcomp e1 f1 ->
      qualcomp e2 f2 ->
      qualcomp (exp_pair qua_bot e1 e2) (exp_pair Q f1 f2)
  | qualcomp_first : forall e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_first e1) (exp_first e2)
  | qualcomp_second : forall e1 e2,
      qualcomp e1 e2 ->
      qualcomp (exp_second e1) (exp_second e2)
.

(** An analogue of qualcomp for stores; this definition corresponds to
    Definition 3.2 in the OOPSLA 2023 paper; thesis §4.1.2, Definition (stripped term). *)
(** Thesis: Definition (stripped store, σ ◁ σ'), §4.1.2. *)
Definition qualcomp_store (s1 : store) (s2 : store) :=
  (forall l v, (LabelMapImpl.MapsTo l v s1) ->
      exists v', (LabelMapImpl.MapsTo l v' s2) /\ qualcomp v v') /\
  (forall l v', (LabelMapImpl.MapsTo l v' s2) ->
      exists v, (LabelMapImpl.MapsTo l v s1) /\ qualcomp v v').

Notation "e1 <e= e2" := (qualcomp e1 e2) (at level 60).
Notation "s1 <s= s2" := (qualcomp_store s1 s2) (at level 60).

#[export] Hint Constructors qualcomp : core.

(**
  We need a notion of store consistency to prove that reduction
  takes the same steps; all locations must be the same even
  if they do not store the same values.
*)
Definition consistent_store (s s' : store) :=
  forall l, (LabelMapImpl.In l s) <-> (LabelMapImpl.In l s').

Lemma consistent_store_symmetric : forall s s',
  consistent_store s s' <-> consistent_store s' s.
Proof with eauto.
  intros. unfold consistent_store... intuition;
  destruct (H l)...
Qed.

#[export] Hint Resolve consistent_store_symmetric : core.

(**
  ...as we need to show that after reduction if two stores
  were consistent they still are consistent as the
  fresh label generated for both was the same label.
  *)
Lemma consistent_fresh_label_for_store : forall s ns,
  consistent_store s ns ->
  fresh_label_for_store s = fresh_label_for_store ns.
Proof with eauto.
  intros * InEquiv; unfold consistent_store in InEquiv.
  assert (forall l, In l (List.map fst (LabelMapImpl.elements s)) <->
                    In l (List.map fst (LabelMapImpl.elements ns))) as Equiv.
  intros; repeat rewrite <- label_map_in_iff_keys in *...
  unfold fresh_label_for_store, exists_fresh_label_for_store; simpl.
  apply Label.fresh_permute...
Qed.


