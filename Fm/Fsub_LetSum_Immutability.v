(** * #<a name="sealed_values"></a># Properties of [value]s that are sealed *)

Lemma irreducible_value : forall e s f s',
  value e ->
  ~ red e s f s'.
Proof with eauto.
  intros * Val Rede. generalize dependent f.
  dependent induction Val; intros; inversion Rede; subst...
Qed.

Lemma qualcomp_value : forall e f,
  expr e ->
  expr f ->
  qualcomp e f ->
  value f ->
  value e.
Proof with eauto.
  intros * Expe Expf Seal Value.
  induction Seal; inversion Value; subst...
  + inversion Expe; inversion Expf; subst...
  + inversion Expe; inversion Expf; subst...
  + inversion Expe; inversion Expf; subst...
Qed.

