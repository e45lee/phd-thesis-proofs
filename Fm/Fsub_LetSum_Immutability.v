Lemma qualcomp_stores_are_consistent : forall s s',
  qualcomp_store s s' ->
  consistent_store s s'.
Proof with eauto.
  intros.
  inversion H; subst...
  split; intros In...
  + destruct In as [v Maps].
    destruct (H0 l v) as [v' [Maps' Less]]...
    eexists v'...
  + destruct In as [v Maps].
    destruct (H1 l v) as [v' [Maps' Less]]...
    eexists v'...
Qed.

#[export] Hint Resolve qualcomp_stores_are_consistent : core.

Lemma qualcomp_store_after_add : forall l s s' v v',
  qualcomp_store s s' ->
  qualcomp v v' ->
  qualcomp_store (LabelMapImpl.add l v s) (LabelMapImpl.add l v' s').
Proof with eauto.
  intros * sLs' vLv'.
  split; intros l1 v1 MapsTo; 
    rewrite LabelMapFacts.add_mapsto_iff in *;
    destruct MapsTo as [[EqL EqV] | [NeqL MapsTo']]; subst...
  + exists v'... split...
    LabelMapFacts.map_iff...
  + destruct sLs' as [Left Right]...
    destruct (Left l1 v1) as [v1' [Maps v1Lv1']]...
    exists v1'... split...
    LabelMapFacts.map_iff; right; split...
  + exists v... split...
    LabelMapFacts.map_iff...
  + destruct sLs' as [Left Right]...
    destruct (Right l1 v1) as [v1' [Maps v1Lv1']]...
    exists v1'... split...
    LabelMapFacts.map_iff; right; split...
Qed.
#[export] Hint Resolve qualcomp_store_after_add : core.


